#!/usr/bin/env python3
"""history-index.py -- regenerate history/INDEX.md from the entry headers.

The failure this prevents: a history directory that is technically complete and
practically unreadable. The convention is one directory per event, one file per
event, which is right for superseding individual claims and useless for finding
one. The index is the only navigable view, and a hand-written index is a second
place for the truth to drift, so it is generated from the entries themselves.

It reads the six-line header every entry carries (When, Status, Supersedes,
Superseded by, Evidence, Confidence) and emits one table row per entry, newest
first. An entry whose header is incomplete is listed with the defect named
rather than skipped, because an entry that cannot be indexed is a defective
entry.

Exit codes: 0 index written, 1 an entry has a defective header, 2 usage.
"""
import argparse
import os
import re
import sys

FIELD = re.compile(r"^\s*-\s+\*\*(?P<key>[^*]+)\*\*:?\s*(?P<val>.*)$", re.M)
WANT = ["When", "Status", "Supersedes", "Superseded by", "Evidence", "Confidence"]


def parse(path):
    with open(path, encoding="utf-8", errors="replace") as fh:
        text = fh.read()
    head = text.split("\n---", 1)[0]
    title = ""
    for line in head.splitlines():
        if line.startswith("# "):
            title = line[2:].strip()
            break
    fields = {m.group("key").strip().rstrip(":").lower(): m.group("val").strip()
              for m in FIELD.finditer(head)}
    return title, fields


def refuse_in_research_checkout(target):
    """The research checkout changes tracked files only through a run (AGENTS.md section 2 rule 14): there, a write to
    a path outside .tmp/ exits 2. This script is for a session in an own clone; a run does the same work with
    scripts/rq. A dry run, a check and a write under .tmp/ go on."""
    import subprocess
    top = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    try:
        r = subprocess.run(["git", "-C", top, "config", "--get", "rq.researchCheckout"], capture_output=True, text=True)
    except OSError:
        return
    if r.stdout.strip().lower() != "true":
        return
    if os.path.normcase(os.path.abspath(target)).startswith(os.path.normcase(os.path.join(top, ".tmp")) + os.sep):
        return
    sys.stderr.write("%s: the research checkout changes records only through a run: scripts/rq open amend TOPIC "
                     "\"RID: what is wrong\" (AGENTS.md section 2 rule 14). This script writes %s, which is for a "
                     "session in an own clone.\n" % (os.path.basename(__file__), target))
    sys.exit(2)


def main():
    ap = argparse.ArgumentParser(
        description="regenerate history/INDEX.md from entry headers")
    ap.add_argument("--root", default="history", help="the history directory")
    ap.add_argument("--check", action="store_true",
                    help="exit 1 if the index on disk is out of date")
    ap.add_argument("--stdout", action="store_true", help="print, do not write")
    args = ap.parse_args()

    root = args.root
    if not os.path.isdir(root):
        print("history-index: no such directory: %s" % root, file=sys.stderr)
        return 2

    rows, defects = [], []
    for name in sorted(os.listdir(root)):
        d = os.path.join(root, name)
        if not os.path.isdir(d):
            continue
        for sub in sorted(os.listdir(d)):
            if not sub.endswith(".md"):
                continue
            path = os.path.join(d, sub).replace("\\", "/")
            title, fields = parse(path)
            missing = [k for k in WANT if k.lower() not in fields]
            if missing:
                defects.append((path, missing))
            rows.append({
                "when": fields.get("when", name),
                "status": fields.get("status", "?"),
                "title": title or sub[:-3].replace("-", " "),
                "supersedes": fields.get("supersedes", "-"),
                "path": path,
            })

    rows.sort(key=lambda r: r["when"], reverse=True)

    out = ["# History index", "",
           "Generated by `python scripts/report/history-index.py`. Do not edit.",
           "One row per entry, newest first. Every entry is a claim this repository",
           "published and later withdrew, or a direction it abandoned. Nothing here",
           "is deleted; a correction is a new entry that supersedes the old one.", "",
           "| when | status | what changed | supersedes | entry |",
           "| --- | --- | --- | --- | --- |"]
    for r in rows:
        sup = r["supersedes"].replace("|", "\\|")
        out.append("| %s | %s | %s | %s | [`%s`](%s) |"
                   % (r["when"], r["status"], r["title"].replace("|", "\\|"),
                      sup, os.path.basename(r["path"]),
                      # INDEX.md sits inside history/, so a path that starts at the
                      # repository root resolves one level too high. Strip the
                      # directory the index lives in, and the link works from where
                      # the reader actually is.
                      os.path.relpath(r["path"], os.path.basename(root)
                                      if os.path.basename(root) == "history" else ".")
                      .replace("\\", "/")))
    if defects:
        out += ["", "## Entries with an incomplete header", "",
                "These cannot be indexed properly. Fix the header, do not reword",
                "the entry: the header fields are what make it findable.", ""]
        for path, missing in defects:
            out.append("- `%s` — missing: %s" % (path, ", ".join(missing)))
    out.append("")
    text = "\n".join(out)

    target = os.path.join(root, "INDEX.md")
    if args.stdout:
        print(text)
    elif args.check:
        current = ""
        if os.path.isfile(target):
            with open(target, encoding="utf-8") as fh:
                current = fh.read()
        if current != text:
            print("history-index: INDEX.md is out of date; run without --check")
            return 1
        print("history-index: up to date, %d entries" % len(rows))
        if defects:
            print("history-index: %d entr%s with an incomplete header (listed in INDEX.md): %s"
                  % (len(defects), "y" if len(defects) == 1 else "ies", ", ".join(p for p, _ in defects[:5])))
    else:
        refuse_in_research_checkout(target)
        with open(target, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(text)
        print("history-index: wrote %d entries, %d defective header(s)"
              % (len(rows), len(defects)))

    return 1 if defects else 0


if __name__ == "__main__":
    sys.exit(main())
